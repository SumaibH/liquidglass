/** Apache-2.0. Generate Flutter's fragment shader from the production SkSL; never a second implementation.
 *
 *   node tool/generate_shader.mjs           write shaders/liquid_glass.frag and lib/src/uniforms.g.dart
 *   node tool/generate_shader.mjs --check   fail if either is stale
 *
 * The source is ports/skia/shaders/material.sksl, the export of the Compose library's material shader.
 * Flutter compiles GLSL for Impeller, and `ImageFilter.shader` binds the live backdrop to the first
 * sampler and its size to the first uniform. So the translation is mechanical:
 *
 * - SkSL types become GLSL types (half and float vectors are both full precision here);
 * - `content.eval(p)` reads the backdrop texture at the padded layer's pixel p, offset by where the
 *   layer sits in the texture (uOrigin). A backdrop filter's input needs no y flip on OpenGL ES:
 *   with the flip Flutter documents for other inputs, an emulator on Impeller's OpenGL ES backend
 *   refracted the page upside down (19 October; see review/atlas/flutter-2026-10-19);
 * - `field.eval(p)` reads a second texture (the sampled distance field; a 1 x 1 placeholder when the
 *   shape is analytic);
 * - `main(coord)` becomes `glassMain(coord)`, called with the padded layer's pixel.
 *
 * One function is replaced rather than translated: `wideAt`, the wide tone kernel. Compose and the
 * CanvasKit port read it from a quarter-scale Gaussian-blurred copy packed below the backdrop; a
 * backdrop filter has one input, so here it is thirteen taps of a Gaussian of the same sigma
 * (uWideKernel). It decides tone only, never detail.
 */
import {readFile, writeFile, mkdir} from 'node:fs/promises';

const here = path => new URL(path, import.meta.url);
const source = (await readFile(here('../../skia/shaders/material.sksl'), 'utf8')).replace(/\r\n/g, '\n');

function replaceOnce(text, pattern, replacement, what) {
  const matches = text.match(new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g'));
  if (!matches || matches.length !== 1) throw new Error(`Shader contract changed: ${what} (${matches?.length ?? 0} matches)`);
  return text.replace(pattern, replacement);
}

let body = source;
body = replaceOnce(body, /^uniform shader content;.*\n/m, '', 'the content child');
body = replaceOnce(body, /^uniform shader field;.*\n/m, '', 'the field child');
body = replaceOnce(body, /half3 wideAt\(float2 p\) \{\n(?:.*\n)*?\}\n/m, `half3 wideAt(float2 p) {
    // Flutter: thirteen taps of a Gaussian with the wide kernel's sigma (see generate_shader.mjs).
    float s = max(uWideKernel, 1.0);
    half3 sum = backdropAt(p);
    float w1 = 0.6065, w2 = 0.1353;
    for (int i = 0; i < 6; i++) {
        float a = float(i) * 1.0471976;
        float b = a + 0.5235988;
        sum += backdropAt(p + float2(cos(a), sin(a)) * s) * half(w1);
        sum += backdropAt(p + float2(cos(b), sin(b)) * (2.0 * s)) * half(w2);
    }
    return sum / half(1.0 + 6.0 * (w1 + w2));
}
`, 'wideAt');
body = body.replace(/\bcontent\.eval\(/g, 'sampleInput(').replace(/\bfield\.eval\(/g, 'sampleField(');
if (/\b(content|field)\.eval\b/.test(body) || /\buniform shader\b/.test(body)) throw new Error('Unhandled shader child');
body = replaceOnce(body, /^half4 main\(float2 coord\) \{/m, 'half4 glassMain(float2 coord) {', 'main');
const types = [['float2x2', 'mat2'], ['float3x3', 'mat3'], ['half4', 'vec4'], ['half3', 'vec3'], ['half2', 'vec2'],
  ['half', 'float'], ['float4', 'vec4'], ['float3', 'vec3'], ['float2', 'vec2']];
for (const [from, to] of types) body = body.replace(new RegExp(`\\b${from}\\b`, 'g'), to);

// The material's own uniforms, in declaration order: the Dart side sets floats by index.
const uniforms = [...body.matchAll(/^uniform\s+(float|vec2|vec3|vec4)\s+(\w+)\s*;/gm)]
  .map(([, type, name]) => ({name, size: {float: 1, vec2: 2, vec3: 3, vec4: 4}[type]}));
if (uniforms.length < 60) throw new Error(`Expected the material's uniforms, found ${uniforms.length}`);

const frag = `// Apache-2.0. Generated by tool/generate_shader.mjs from ports/skia/shaders/material.sksl.
// Do not edit: \`node tool/generate_shader.mjs --check\` fails when this drifts from the source.
#version 460 core
#include <flutter/runtime_effect.glsl>
precision highp float;

// ImageFilter.shader binds the backdrop's size to the first uniform and the backdrop to the first sampler.
uniform vec2 uTexSize;
uniform vec2 uOrigin;     // the padded layer's top-left in the backdrop texture, px
uniform vec2 uFieldSize;  // the distance field texture's size, px (1 x 1 when the shape is analytic)
uniform sampler2D uTexture;
uniform sampler2D uField;
out vec4 fragColor;

vec4 sampleInput(vec2 p) {
    return texture(uTexture, (p + uOrigin) / uTexSize);
}

vec4 sampleField(vec2 p) {
    return texture(uField, p / uFieldSize);
}

${body.trimEnd()}

void main() {
    fragColor = glassMain(FlutterFragCoord().xy - uOrigin);
}
`;

const dart = `// Apache-2.0. Generated by tool/generate_shader.mjs; do not edit.
// The material uniforms of shaders/liquid_glass.frag in declaration order, after uTexSize, uOrigin and
// uFieldSize (floats 0 to 5).
part of '../liquiglass.dart';

const List<(String, int)> _materialUniforms = [
${uniforms.map(u => `  ('${u.name}', ${u.size}),`).join('\n')}
];
`;

const outputs = [['../shaders/liquid_glass.frag', frag], ['../lib/src/uniforms.g.dart', dart]];
if (process.argv.includes('--check')) {
  const stale = [];
  for (const [path, text] of outputs) {
    const actual = await readFile(here(path), 'utf8').catch(() => null);
    if (actual?.replace(/\r\n/g, '\n') !== text) stale.push(path);
  }
  if (stale.length) throw new Error(`Generated files are stale (${stale.join(', ')}). Run node tool/generate_shader.mjs.`);
  console.log(`liquid_glass.frag and uniforms.g.dart match material.sksl (${uniforms.length} uniforms).`);
} else {
  for (const [path, text] of outputs) {
    await mkdir(new URL('.', here(path)), {recursive: true});
    await writeFile(here(path), text);
  }
  console.log(`Generated liquid_glass.frag and uniforms.g.dart (${uniforms.length} material uniforms).`);
}
