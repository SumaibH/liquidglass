// Apache-2.0. Writes selector-material-data.mjs from the Kotlin export
// (fixtures/selector-material.json, GlassSelectorPortMaterialTest); --check fails on drift.
import {readFile, writeFile} from 'node:fs/promises';

const here = new URL('.', import.meta.url);
const fixture = JSON.parse(await readFile(new URL('fixtures/selector-material.json', here), 'utf8'));
const data = {dpFields: fixture.dpFields, fold: fixture.fold, styles: fixture.styles};
const text = '// Generated by generate-selector-material.mjs from fixtures/selector-material.json\n' +
  '// (the Compose Calm selector and bar styles as shader uniforms). Do not edit.\n' +
  `export const CALM_SELECTOR_MATERIAL_DATA = Object.freeze(${JSON.stringify(data)});\n`;
const target = new URL('selector-material-data.mjs', here);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') !== text)
    throw new Error('selector-material-data.mjs is stale. Run node generate-selector-material.mjs in ports/skia.');
} else await writeFile(target, text);
